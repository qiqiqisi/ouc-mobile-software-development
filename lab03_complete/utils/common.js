const FAVORITES_KEY = 'lab03_favorite_ids';
const HISTORY_KEY = 'lab03_history';
const PROFILE_KEY = 'lab03_user_profile';
const LOGIN_STATE_KEY = 'lab03_logged_in';

function getNewsList() {
  return NEWS.slice();
}

function getSwiperNews() {
  return NEWS.filter(item => item.swiper && item.cover);
}

function getCategories() {
  const categories = NEWS
    .map(item => item.category)
    .filter(Boolean);

  return ['全部', ...new Set(categories)];
}

function getSearchableText(item) {
  const contentText = (item.content || [])
    .map(block => block.text || block.caption || '')
    .join(' ');

  return [
    item.title,
    item.author,
    item.source,
    item.category,
    item.lead,
    contentText
  ]
    .filter(Boolean)
    .join(' ')
    .toLowerCase();
}

function filterNews(options = {}) {
  const keyword = String(options.keyword || '').trim().toLowerCase();
  const category = options.category || '全部';

  return NEWS.filter(item => {
    const categoryMatched = category === '全部' || item.category === category;
    const keywordMatched = !keyword || getSearchableText(item).includes(keyword);

    return categoryMatched && keywordMatched;
  });
}

function getNewsById(id) {
  return NEWS.find(item => item.id === String(id)) || null;
}

function getFavoriteIds() {
  const stored = wx.getStorageSync(FAVORITES_KEY);
  if (!Array.isArray(stored)) {
    return [];
  }

  return [...new Set(
    stored
      .map(id => String(id))
      .filter(id => Boolean(getNewsById(id)))
  )];
}

function isFavorite(id) {
  return getFavoriteIds().includes(String(id));
}

function toggleFavorite(id) {
  const newsId = String(id);
  let ids = getFavoriteIds();
  const exists = ids.includes(newsId);

  if (exists) {
    ids = ids.filter(item => item !== newsId);
  } else {
    ids.unshift(newsId);
  }

  wx.setStorageSync(FAVORITES_KEY, ids);
  return !exists;
}

function getFavoriteNews() {
  const ids = getFavoriteIds();
  return ids.map(id => getNewsById(id)).filter(Boolean);
}

function removeFavorite(id) {
  const newsId = String(id);
  const ids = getFavoriteIds().filter(item => item !== newsId);
  wx.setStorageSync(FAVORITES_KEY, ids);
}

function removeFavorites(ids) {
  const removeSet = new Set((ids || []).map(id => String(id)));
  const next = getFavoriteIds().filter(id => !removeSet.has(id));
  wx.setStorageSync(FAVORITES_KEY, next);
}

function clearFavorites() {
  wx.removeStorageSync(FAVORITES_KEY);
}

function getHistoryRecords() {
  const records = wx.getStorageSync(HISTORY_KEY);

  if (!Array.isArray(records)) {
    return [];
  }

  return records
    .filter(item => item && getNewsById(item.id))
    .map(item => ({
      id: String(item.id),
      viewedAt: Number(item.viewedAt) || 0
    }));
}

function addHistory(id) {
  const newsId = String(id);

  if (!getNewsById(newsId)) {
    return;
  }

  const next = getHistoryRecords()
    .filter(item => item.id !== newsId);

  next.unshift({
    id: newsId,
    viewedAt: Date.now()
  });

  // 只保留最近 20 条，避免本地记录无限增长。
  wx.setStorageSync(HISTORY_KEY, next.slice(0, 20));
}

function getHistoryNews() {
  return getHistoryRecords()
    .map(record => {
      const article = getNewsById(record.id);
      if (!article) {
        return null;
      }

      return {
        ...article,
        viewedAt: record.viewedAt
      };
    })
    .filter(Boolean);
}

function removeHistory(id) {
  const newsId = String(id);
  const records = getHistoryRecords()
    .filter(item => item.id !== newsId);

  wx.setStorageSync(HISTORY_KEY, records);
}

function removeHistories(ids) {
  const removeSet = new Set((ids || []).map(id => String(id)));
  const next = getHistoryRecords()
    .filter(item => !removeSet.has(item.id));

  wx.setStorageSync(HISTORY_KEY, next);
}

function clearHistory() {
  wx.removeStorageSync(HISTORY_KEY);
}

function getProfile() {
  return wx.getStorageSync(PROFILE_KEY) || null;
}

function saveProfile(profile) {
  wx.setStorageSync(PROFILE_KEY, profile);
}

function hasSavedProfile() {
  const profile = getProfile();
  return Boolean(profile && profile.avatarUrl && profile.nickname);
}

function isLoggedIn() {
  return Boolean(wx.getStorageSync(LOGIN_STATE_KEY)) && hasSavedProfile();
}

function setLoggedIn(value) {
  if (value) {
    wx.setStorageSync(LOGIN_STATE_KEY, true);
  } else {
    wx.removeStorageSync(LOGIN_STATE_KEY);
  }
}

function clearProfile() {
  wx.removeStorageSync(PROFILE_KEY);
  wx.removeStorageSync(LOGIN_STATE_KEY);
}

